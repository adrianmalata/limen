/* PL: Generator indeksu katalogu spec/ autora Limena (etap 1). Czyta wyłącznie listę ścieżek i rozmiary plików
   z drzewa gita dla podanego refa (domyślnie rebuild-base), bez otwierania ich treści, i zapisuje tabelę
   feature'ów według statusu oraz listę plików badań do evidence/spec-index.md, atomowo (atomic-write.mjs, D-018).
   Stan: działający. */
// Usage: node adrian-rebuild/tools/spec-index.mjs [ref] [output]
import { execFileSync } from "node:child_process";
import { writeAtomic } from "./atomic-write.mjs";

const ref = process.argv[2] ?? "rebuild-base";
const output = process.argv[3] ?? "adrian-rebuild/evidence/spec-index.md";

/** Every blob under spec/ at `ref` as { path, bytes }; `git ls-tree -l` gives sizes without reading contents. */
function specBlobs() {
	const listing = execFileSync("git", ["ls-tree", "-r", "-l", "-z", ref, "spec"], { encoding: "utf8" });
	return listing
		.split("\0")
		.filter(Boolean)
		.map((entry) => {
			const [meta, path] = entry.split("\t");
			return { path, bytes: Number(meta.trim().split(/\s+/)[3]) };
		});
}

/**
 * The feature a path belongs to: spec/features/<status>/<folder>/..., where done features sit one level deeper
 * under a month folder (spec/features/done/2026-10/<folder>/...).
 */
function featureOf(path) {
	const parts = path.split("/");
	const monthly = /^\d{4}-\d{2}$/.test(parts[3] ?? "");
	const depth = monthly ? 6 : 5;
	if (parts[1] !== "features" || parts.length < depth) {
		return undefined;
	}
	return { status: parts[2], folder: monthly ? `${parts[3]}/${parts[4]}` : parts[3] };
}

/** Groups features as status → folder → { files, bytes }. */
function features(blobs) {
	const byStatus = new Map();
	for (const { path, bytes } of blobs) {
		const feature = featureOf(path);
		if (!feature) {
			continue;
		}
		const { status, folder } = feature;
		const group = byStatus.get(status) ?? new Map();
		const entry = group.get(folder) ?? { files: 0, bytes: 0 };
		entry.files += 1;
		entry.bytes += bytes;
		group.set(folder, entry);
		byStatus.set(status, group);
	}
	return byStatus;
}

function featureTables(byStatus) {
	const lines = [];
	for (const [status, group] of [...byStatus].sort(([a], [b]) => a.localeCompare(b))) {
		lines.push(`### ${status} (${group.size})`, "", "| Feature | Files | Bytes |", "|---|---|---|");
		for (const [folder, { files, bytes }] of [...group].sort(([a], [b]) => a.localeCompare(b))) {
			lines.push(`| \`${folder}\` | ${files} | ${bytes} |`);
		}
		lines.push("");
	}
	return lines;
}

function fileTable(title, blobs) {
	const rows = blobs.map(({ path, bytes }) => `| \`${path}\` | ${bytes} |`);
	return [`## ${title} (${blobs.length})`, "", "| File | Bytes |", "|---|---|", ...rows, ""];
}

const blobs = specBlobs();
const byStatus = features(blobs);
const featureCount = [...byStatus.values()].reduce((sum, group) => sum + group.size, 0);
const totalBytes = blobs.reduce((sum, blob) => sum + blob.bytes, 0);
const research = blobs.filter(({ path }) => path.startsWith("spec/research/"));
const other = blobs.filter(({ path }) => !path.startsWith("spec/research/") && !path.startsWith("spec/features/"));
const statusCounts = [...byStatus].map(([status, group]) => `${status} ${group.size}`).join(", ");

const text = [
	`<!-- PL: Indeks katalogu spec/ autora przy refie ${ref}, wygenerowany przez tools/spec-index.mjs z samych ścieżek`,
	`i rozmiarów plików, bez czytania ich treści. Zawiera ${featureCount} folderów feature'ów według statusu`,
	`(${statusCounts}), ${research.length} plików badań i pozostałe pliki spec/. Stan: wygenerowany; nie edytować ręcznie. -->`,
	"",
	`# Index of \`spec/\` at \`${ref}\``,
	"",
	`Generated by \`node adrian-rebuild/tools/spec-index.mjs ${ref}\` from \`git ls-tree\` paths and sizes only.`,
	`${blobs.length} files, ${totalBytes} bytes. Features per status: ${statusCounts}.`,
	"",
	"## Features",
	"",
	...featureTables(byStatus),
	...fileTable("Research", research),
	...fileTable("Other spec files", other),
].join("\n");
writeAtomic(output, text);
console.log(
	`wrote ${output}: ${blobs.length} files, ${featureCount} feature folders, ${research.length} research files`,
);
