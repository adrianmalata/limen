/* PL: Szkic generatora tablicy `spec/build.md` według T-23 po poprawkach Adriana: plik zawiera wyłącznie to, co
   wynika z treści gita w danym commicie (foldery ticketów, front matter, outcome.md); stan jobów i otwarte pytania z
   .limen/ pokazują na żywo limen status i stopka. Fikstura odwzorowuje kształt projektu synchronizer po M1 (21
   ticketów w done/, początek M2); tytuły i daty są syntetyczne. Stan: szkic do oceny w wywiadzie etapu 3; kończy się
   kodem 1, gdy kotwica milestone nie istnieje albo linia przekracza 100 znaków. */
// Usage: node adrian-rebuild/evidence/taste/board-draft.mjs   (prints the generated spec/build.md for the fixture)

const WIDTH = 100;
const PROVEN_SHOWN = 10;
const DROPPED_SHOWN = 3;

// Synthetic fixture: the shape of synchronizer after M1, not its content.
const DOCS_ANCHORS = new Set(["docs/plan.md#m1-full-sync", "docs/plan.md#m2-incremental-sync"]);
const M1_TITLES = [
	"A config file names the two folders to sync",
	"A first run copies every file to the other side",
	"Sync skips files listed in an ignore file",
	"A run stops with a clear error when a folder is missing",
	"File times survive a copy",
	"Large files copy in chunks without holding them in memory",
	"A run writes a log line per copied file",
	"Sync refuses to run twice at the same time",
	"Symbolic links are copied as links",
	"A dry run lists what would change",
	"Sync state survives a restart",
	"Files with the same content are not copied again",
	"A run reports how long it took",
	"Empty folders are created on the other side",
	"File permissions survive a copy",
	"A run can be limited to one subfolder",
	"Errors on one file do not stop the run",
	"The CLI prints its version",
	"A run exits with code 1 when any file failed",
	"The ignore file supports comments",
	"Sync runs from a config file",
];
const TICKETS = [
	...M1_TITLES.map((title, index) => ({
		// F017 was dropped in M1, and a number stays taken for life, so the landed tickets skip it.
		number: index + 1 + (index >= 16 ? 1 : 0),
		title,
		lane: "done",
		milestone: "docs/plan.md#m1-full-sync",
		landed: `2026-${index < 12 ? "10" : "11"}-${String((index % 12) + 2).padStart(2, "0")}`,
	})),
	{
		number: 23,
		title: "Changes sync incrementally after the first run",
		lane: "active",
		milestone: "docs/plan.md#m2-incremental-sync",
	},
	{
		number: 24,
		title: "Deleted files are removed on the other side",
		lane: "planned",
		milestone: "docs/plan.md#m2-incremental-sync",
	},
	{
		number: 25,
		title: "A run prints one summary line",
		lane: "planned",
		milestone: "docs/plan.md#m2-incremental-sync",
	},
	{ number: 17, title: "Sync over FTP", lane: "dropped", dropped: "2026-10-30" },
];

const id = (number) => `F${String(number).padStart(3, "0")}`;

function milestoneSection(open) {
	const anchors = [...new Set(open.map((ticket) => ticket.milestone).filter(Boolean))];
	const missing = anchors.filter((anchor) => !DOCS_ANCHORS.has(anchor));
	if (missing.length) {
		throw new Error(`milestone anchor not found in docs/: ${missing.join(", ")}`);
	}
	return anchors.map((anchor) => {
		const tickets = open.filter((ticket) => ticket.milestone === anchor);
		const active = tickets.filter((ticket) => ticket.lane === "active").length;
		return `- ${anchor} · ${tickets.length} open: ${active} active, ${tickets.length - active} planned`;
	});
}

function provenSection(done) {
	const landed = [...done].sort((a, b) => b.landed.localeCompare(a.landed) || b.number - a.number);
	const lines = landed
		.slice(0, PROVEN_SHOWN)
		.map((ticket) => `- ${ticket.title} (${id(ticket.number)}) · ${ticket.landed}`);
	const older = landed.length - PROVEN_SHOWN;
	return older > 0 ? [...lines, `- ${older} earlier landed tickets`] : lines;
}

function render() {
	const lane = (name) => TICKETS.filter((ticket) => ticket.lane === name);
	const open = [...lane("active"), ...lane("planned")];
	const section = (title, lines, note) => [
		`## ${title}`,
		"",
		...(note ? [note, ""] : []),
		...(lines.length ? lines : ["- none"]),
		"",
	];
	return [
		"# Build",
		"",
		"<!-- Generated by limen spec fix from spec/features/ at this commit. Do not edit: limen ticket check",
		"     refuses a file that differs from the generated one. Jobs and open questions: limen status. -->",
		"",
		...section("Milestone", milestoneSection(open)),
		...section(
			"Now",
			lane("active").map((ticket) => `- ${ticket.title} (${id(ticket.number)})`),
		),
		...section(
			"Next",
			lane("planned")
				.sort((a, b) => a.number - b.number)
				.map((ticket) => `- ${ticket.title} (${id(ticket.number)})`),
		),
		...section("Proven", provenSection(lane("done")), "outcomes: spec/features/done/<month>/<FNNN-slug>/outcome.md"),
		...section(
			"Dropped",
			lane("dropped")
				.slice(0, DROPPED_SHOWN)
				.map((ticket) => `- ${ticket.title} (${id(ticket.number)}) · ${ticket.dropped}`),
		),
	];
}

try {
	const lines = render();
	console.log(lines.join("\n").trimEnd());
	const wide = lines.filter((line) => line.length > WIDTH);
	for (const line of wide) {
		console.error(`wider than ${WIDTH}: ${line.length}: ${line}`);
	}
	process.exitCode = wide.length === 0 ? 0 : 1;
} catch (error) {
	console.error(error.message);
	process.exitCode = 1;
}
